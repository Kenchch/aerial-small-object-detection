"""An accuracy figure without provenance is a number, not a measurement.

reports/evaluation_test.json carried a provenance block that had been typed by
hand; reports/evaluation.json carried none at all. That is the usual shape of
this problem -- the file someone remembered has provenance, the file that came
first does not, and neither can be checked against the run that produced it.

Both are now generated by `_provenance` in src/evaluate.py, so these tests hold
the two files to the same contract and check the parts that are checkable.
"""

import json
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]

REPORTS = ("evaluation.json", "evaluation_test.json")

REQUIRED = {
    "run_date",
    "checkpoint_sha256",
    "split",
    "data",
    "imgsz",
    "device",
    "torch",
    "ultralytics",
    "cuda",
    "gpu",
    "selection",
    "data_root_overridden",
}


def _report(name: str) -> dict:
    return json.loads((ROOT / "reports" / name).read_text(encoding="utf-8"))


@pytest.mark.parametrize("name", REPORTS)
def test_every_evaluation_records_its_provenance(name):
    provenance = _report(name).get("provenance")
    assert provenance, f"{name} has no provenance block"
    missing = REQUIRED - set(provenance)
    assert not missing, f"{name} is missing {sorted(missing)}"


@pytest.mark.parametrize("name", REPORTS)
def test_both_reports_used_the_same_checkpoint(name):
    """The two files are compared with each other -- the README states the gap
    between them -- which is only meaningful if they ran the same weights."""
    assert (
        _report(name)["provenance"]["checkpoint_sha256"]
        == (_report("evaluation.json")["provenance"]["checkpoint_sha256"])
    )


@pytest.mark.parametrize("name", REPORTS)
def test_the_release_is_claimed_only_when_the_digest_matches(name):
    """`checkpoint_release` is emitted by _provenance only when the checkpoint
    hashes to the released one. Evaluating some other checkpoint is a perfectly
    valid thing to do; saying it came from the release would not be.
    """
    from evaluate import RELEASE_SHA256, RELEASE_URL

    provenance = _report(name)["provenance"]
    claimed = "checkpoint_release" in provenance
    matches = provenance["checkpoint_sha256"] == RELEASE_SHA256
    assert claimed == matches, (
        "the report claims the release without matching its digest"
        if claimed
        else "the digest is the release's and the report does not say so"
    )
    if claimed:
        assert provenance["checkpoint_release"] == RELEASE_URL


def test_the_pinned_release_digest_is_the_one_the_gpu_test_downloads():
    """Two copies of a hash is two chances to update one of them."""
    from evaluate import RELEASE_SHA256

    assert RELEASE_SHA256 in (ROOT / "tests/test_gpu.py").read_text(encoding="utf-8")


@pytest.mark.parametrize("doc", ["README.md", "docs/DESIGN.md"])
def test_the_documented_download_fails_loudly_and_is_verified(doc):
    """Without -f, curl saved GitHub's 9-byte 'Not Found' page as best.pt and
    exited 0; and nothing checked the digest the docs printed beside it."""
    from evaluate import RELEASE_SHA256, RELEASE_URL

    asset = RELEASE_URL.replace("/releases/tag/", "/releases/download/") + "/best.pt"
    text = (ROOT / doc).read_text(encoding="utf-8")
    assert f"curl -fL --retry 3 -o runs/n_1024/weights/best.pt \\\n  {asset}" in text
    assert f'echo "{RELEASE_SHA256}  runs/n_1024/weights/best.pt" | sha256sum -c -' in (
        text
    )
    assert "curl -L " not in text, "an unchecked download is still documented"


def test_the_docker_tracking_example_writes_to_the_mounted_output():
    """track.py's defaults are reports/ inside the image, which nothing mounts:
    the documented command's results stayed in the container."""
    design = (ROOT / "docs/DESIGN.md").read_text(encoding="utf-8")
    command = design[design.index("aerial-detection src/track.py") :]
    command = command[: command.index("\n\n")]
    assert "--report /out/" in command
    assert "--out /out/" in command


@pytest.mark.parametrize("name", REPORTS)
def test_no_machine_specific_path_reached_a_committed_report(name):
    """`_portable` exists for this. An absolute path from whichever machine last
    ran the evaluation says nothing to a reader and quietly publishes a
    directory layout -- the same reason the cuDNN directory stays out of
    benchmark.json.
    """
    text = json.dumps(_report(name))
    for marker in (":\\\\", ":/Users/", "/home/", "C:", "D:"):
        assert marker not in text, f"{name} contains {marker!r}"


@pytest.mark.parametrize("name", REPORTS)
def test_the_data_spec_named_is_one_the_repository_carries(name):
    """The point of --data-root: the report names the committed spec and records
    the override as a field, rather than a path or a parenthetical apology."""
    provenance = _report(name)["provenance"]
    assert (ROOT / provenance["data"]).is_file(), (
        f"{name} names a data spec this repository does not contain: "
        f"{provenance['data']}"
    )
    assert isinstance(provenance["data_root_overridden"], bool)
